def sprite_16x16(rows: list[str]) -> bytes:
    """Two 8x16 columns = 4 tiles (L0,L1,R0,R1) for 8x16 sprite mode."""
    left_top = [r[:8] for r in rows[:8]]
    left_bot = [r[:8] for r in rows[8:16]]
    right_top = [r[8:16] for r in rows[:8]]
    right_bot = [r[8:16] for r in rows[8:16]]
    return tile(left_top) + tile(left_bot) + tile(right_top) + tile(right_bot)


