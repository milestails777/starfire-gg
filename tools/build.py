def gg_color(r: int, g: int, b: int) -> bytes:
    """12-bit Game Gear CRAM: byte0=R|G, byte1=B."""
    r4 = r & 0xF
    g4 = g & 0xF
    b4 = b & 0xF
    return bytes((r4 | (g4 << 4), b4))


def build_tiles() -> bytes:
    data = bytearray()
    for ch in [" "] + list("0123456789") + [chr(c) for c in range(ord("A"), ord("Z") + 1)]:
        data += tile(FONT[ch])
    # 37 tiles so far (space + 10 + 26)
    data += tile(FLOOR_TILE)
    data += tile(COVER_TILE)
    while len(data) < 64 * 32:
        data += tile(FONT[" "])
    data += sprite_16x16(SHIP)
    data += sprite_16x16(ENEMY)
    data += tile(BULLET[:8]) + tile(BULLET[8:])
    while len(data) % 256:
        data += b"\x00"
    return bytes(data)


def write_header(rom: bytearray) -> None:
    rom[0x7FF0:0x7FF8] = b"TMR SEGA"
    rom[0x7FF8] = 0
    rom[0x7FF9] = 0
    checksum = sum(rom[0:0x7FF0]) & 0xFFFF
    rom[0x7FFA] = checksum & 0xFF
    rom[0x7FFB] = checksum >> 8
    # product code 97001, version 0
    rom[0x7FFC] = 0x01
    rom[0x7FFD] = 0x70
    rom[0x7FFE] = 0x09
    rom[0x7FFF] = 0x4C  # export Game Gear, 32 KB


